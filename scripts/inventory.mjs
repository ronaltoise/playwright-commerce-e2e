#!/usr/bin/env node
// Writes docs/TEST-INVENTORY.md from the tests themselves, so the catalogue can't drift from the
// code. `--check` fails if the file is out of date, which is how the pipeline enforces it.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';

const OUTPUT = 'docs/TEST-INVENTORY.md';

const AREAS = {
  account: 'Accounts and orders',
  admin: 'Admin',
  api: 'API contract',
  auth: 'Sign-in',
  cart: 'Cart and coupons',
  catalog: 'Catalogue',
  checkout: 'Checkout and payment',
  subscription: 'Subscriptions',
};

const listed = spawnSync('npx', ['playwright', 'test', '--project=stable', '--list', '--reporter=json'], {
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
if (listed.status !== 0) {
  console.error(listed.stderr || listed.stdout);
  process.exit(1);
}

function collect(suite, into = []) {
  for (const spec of suite.specs ?? []) {
    if (spec.file.includes('specs/')) into.push(spec);
  }
  for (const child of suite.suites ?? []) collect(child, into);
  return into;
}

const specs = JSON.parse(listed.stdout).suites.flatMap((suite) => collect(suite));
const byArea = {};
for (const spec of specs) (byArea[/specs\/([^/]+)\//.exec(spec.file)[1]] ??= []).push(spec);
const ids = specs.map((spec) => /^([A-Z]+-\d+) > /.exec(spec.title)?.[1]);

const missing = specs.filter((_, i) => !ids[i]).map((spec) => spec.title);
const repeated = ids.filter((id, i) => ids.indexOf(id) !== i);
if (missing.length || repeated.length) {
  console.error(`Every test needs a unique ID like "CAT-01 > ...".\nNo ID: ${missing}\nRepeated: ${repeated}`);
  process.exit(1);
}

const smoke = specs.filter((spec) => spec.tags.includes('smoke')).length;
const sections = Object.keys(AREAS)
  .filter((area) => byArea[area])
  .map((area) => {
    const rows = byArea[area]
      .sort((a, b) => a.title.localeCompare(b.title, 'en', { numeric: true }))
      .map((spec) => {
        const [id, ...title] = spec.title.split(' > ');
        const tags = spec.tags.map((tag) => `@${tag}`).join(' ');
        return `| ${id} | ${title.join(' > ').replaceAll('|', '/')} | ${tags} | \`${spec.file.replace('specs/', '')}\` |`;
      });
    return [
      `## ${AREAS[area]} (${rows.length})`,
      '',
      '| ID | What it checks | Tags | Spec |',
      '|---|---|---|---|',
      ...rows,
      '',
    ].join('\n');
  });

const text = [
  '# Test inventory',
  '',
  'Generated from the tests by `npm run inventory`. Do not edit this file by hand: the pipeline fails if it is out of date.',
  '',
  `**${specs.length} tests**, ${smoke} of them \`@smoke\`.`,
  '',
  ...sections,
].join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (current !== text) {
    console.error(`${OUTPUT} is out of date. Run \`npm run inventory\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date (${specs.length} tests).`);
} else {
  fs.writeFileSync(OUTPUT, text);
  console.log(`Wrote ${OUTPUT} (${specs.length} tests).`);
}
